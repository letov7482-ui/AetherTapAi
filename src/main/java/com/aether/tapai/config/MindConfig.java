    private static void add(String key, String... responses) {
        memory.put(key.toLowerCase().trim(), Arrays.asList(responses));
    }

    public static String findBest(String input) {
        String lower = input.toLowerCase().trim();
        if (memory.containsKey(lower)) {
            List<String> answers = memory.get(lower);
            return answers.get(RANDOM.nextInt(answers.size()));
        }
        for (var entry : memory.entrySet()) {
            String key = entry.getKey();
            if (lower.contains(key) || key.contains(lower)) {
                List<String> answers = entry.getValue();
                return answers.get(RANDOM.nextInt(answers.size()));
            }
        }
        return null;
    }

    public static void addCustom(String key, String value) {
        memory.putIfAbsent(key.toLowerCase().trim(), new ArrayList<>());
        memory.get(key.toLowerCase().trim()).add(value.trim());
        saveCustom(key, value);
    }

    private static void load() {
        try {
            Files.createDirectories(CONFIG_PATH.getParent());
            if (CONFIG_PATH.toFile().exists()) {
                for (String line : Files.readAllLines(CONFIG_PATH)) {
                    String[] p = line.split("->", 2);
                    if (p.length == 2) {
                        addCustom(p[0].trim(), p[1].trim());
                    }
                }
            }
        } catch (Exception ignored) {}
    }

    private static void saveCustom(String key, String value) {
        try (FileWriter fw = new FileWriter(CONFIG_PATH.toFile(), true);
             PrintWriter pw = new PrintWriter(fw)) {
            pw.println(key + " -> " + value);
        } catch (Exception ignored) {}
    }
